export function translateSeverity(
  severity: string,
  language: Language,
): string {
  const keys: Record<string, TranslationKey> = {
    Low: 'severityLow',
    Medium: 'severityMedium',
    High: 'severityHigh',
    Critical: 'severityCritical',
  };

  const key = keys[severity];
  return key ? getTranslation(language, key) : severity;
}
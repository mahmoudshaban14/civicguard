export type TranslationKey = keyof typeof translations.en;

export function getTranslation(
  language: Language,
  key: TranslationKey,
): string {
  return translations[language][key];
}

export function translateStatus(
  status: string,
  language: Language,
): string {
  const knownStatuses: Record<string, TranslationKey> = {
    submitted: 'submitted',
    ai_analyzed: 'ai_analyzed',
    assigned: 'assigned',
    under_review: 'under_review',
    in_progress: 'in_progress',
    resolved: 'resolved_status',
    rejected: 'rejected',
    manual_review_required: 'manual_review_required',
    duplicate: 'duplicate',
    invalid: 'invalid',
    escalated: 'escalated',
  };

  const key = knownStatuses[status];

  if (key) {
    return getTranslation(language, key);
  }

  return status.replaceAll('_', ' ');
}

export function translateCategory(
  category: string,
  language: Language,
): string {
  const normalized = category.toLowerCase().replaceAll('_', ' ');

  if (language === 'en') {
    return normalized;
  }

  const knownCategories: Record<string, string> = {
    roads: 'الطرق',
    road: 'الطرق',
    lighting: 'الإنارة',
    street_lighting: 'إنارة الشوارع',
    garbage: 'القمامة',
    waste: 'المخلفات',
    water: 'المياه',
    sanitation: 'الصرف الصحي',
    electricity: 'الكهرباء',
    traffic: 'المرور',
    public_safety: 'السلامة العامة',
    buildings: 'المباني',
    other: 'أخرى',
  };

  return knownCategories[category.toLowerCase()] ?? normalized;
}
